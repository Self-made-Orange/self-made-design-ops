import { readFileSync, writeFileSync } from 'node:fs';
import { LOCALES, matchLocale, languageState, formatMessage, localizedURL,
  localizedSiteLink, readCatalogState, catalogStateURL } from './i18n-core.mjs';

export function buildI18n() {
  const messages = JSON.parse(readFileSync(new URL('./locales/messages.json', import.meta.url), 'utf8'));
  const readme = readFileSync(new URL('../README.md', import.meta.url), 'utf8');
  for (const locale of LOCALES) {
    if (!readme.includes(locale.name) || (locale.code !== 'en' && !readme.includes(locale.readme))) {
      throw new Error(`Website locale is missing from README: ${locale.code}`);
    }
  }
  const placeholders = (s) => JSON.stringify((s.match(/\{\w+\}/g) || []).sort());
  for (const [source, translations] of Object.entries(messages)) {
    for (const { code } of LOCALES.slice(1)) {
      if (!translations[code]?.trim()) throw new Error(`Missing ${code}: ${source}`);
    }
    // English copy overrides keep source keys stable for generated content.
    for (const [code, value] of Object.entries(translations)) {
      if (!LOCALES.some((locale) => locale.code === code) || !value?.trim()) {
        throw new Error(`Invalid translation in ${code}: ${source}`);
      }
      if (placeholders(source) !== placeholders(value)) {
        throw new Error(`Changed placeholders in ${code}: ${source}`);
      }
    }
  }
  const runtime = readFileSync(new URL('./i18n-runtime.js', import.meta.url), 'utf8');
  const bundle = `// Generated by site/build.mjs. Edit site/locales/messages.json or site/i18n-*.\n(() => {\n'use strict';\n` +
    `const LOCALES = ${JSON.stringify(LOCALES)};\nconst MESSAGES = ${JSON.stringify(messages)};\n` +
    [matchLocale, languageState, formatMessage, localizedURL, localizedSiteLink,
      readCatalogState, catalogStateURL].map(String).join('\n') + '\n' + runtime + '\n})();\n';
  writeFileSync(new URL('../docs/assets/i18n.js', import.meta.url), bundle);
  return Object.keys(messages).length;
}
